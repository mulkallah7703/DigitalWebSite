function hash32(input: string): number {
  let h = 2166136261
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  let x = h >>> 0
  x = Math.imul(x ^ (x >>> 16), 0x7feb352d)
  x = Math.imul(x ^ (x >>> 15), 0x846ca68b)
  return (x ^ (x >>> 16)) >>> 0
}

function uniq(list: string[]) {
  const seen = new Set<string>()
  const out: string[] = []
  for (const item of list) {
    if (seen.has(item)) continue
    seen.add(item)
    out.push(item)
  }
  return out
}

const GIVEN = uniq(GIVEN_NAMES)
const FAMILIES = uniq(FAMILY_NAMES).filter((name) => !name.includes(' ') || name.startsWith('آل '))

function reviewName(salt: number, index: number) {
  const given = GIVEN[(salt + index * 7) % GIVEN.length]
  const family = FAMILIES[(Math.floor(salt / 17) + index * 8) % FAMILIES.length]
  return `${given} ${family}`
}

function plainTopic(description: string, productName: string) {
  const plain = description
    .replace(/<[^>]*>/g, ' ')
    .replace(/&[a-z#0-9]+;/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  const words = plain.split(' ').filter(Boolean).slice(0, 4).join(' ')
  if (words.length < 8) return ''
  if (!/[\u0600-\u06FF]/.test(words)) return ''
  if (productName && (words === productName || words.includes(productName) || productName.includes(words))) return ''
  return words
}

const SHADES = ['اليوم', 'فعلًا', 'بصراحة', 'جدًا', 'تمامًا', 'بوضوح', 'سريعًا', 'أكيد']

function sig(noun: string, adj: string, adj2: string, boost: string) {
  return `${noun} ${adj} و${adj2} ${boost}`
}

function take(value: number, size: number) {
  return { item: value % size, rest: Math.floor(value / size) }
}

function phraseSpace(length: number) {
  const dialects = DIALECTS.length
  const nouns = NOUNS.length
  const adjs = ADJS.length
  const adj2 = adjs - 1
  const boosts = DIALECTS[0].boosts.length
  const openers = DIALECTS[0].openers.length
  const lines = DIALECTS[0].lines.length
  const tails = DIALECTS[0].tails.length
  const core = dialects * nouns * adjs * adj2 * boosts
  if (length === 0) return core * SHADES.length
  if (length === 1) return core * openers
  if (length === 2) return core * lines
  return core * lines * NOTES.length * tails
}

function commentAt(length: number, phrase: number, topic: string) {
  let cursor = take(phrase, DIALECTS.length)
  const dialect = DIALECTS[cursor.item]
  cursor = take(cursor.rest, NOUNS.length)
  const noun = NOUNS[cursor.item]
  cursor = take(cursor.rest, ADJS.length)
  const adjIndex = cursor.item
  const adj = ADJS[adjIndex]
  cursor = take(cursor.rest, ADJS.length - 1)
  const adj2 = ADJS[cursor.item < adjIndex ? cursor.item : cursor.item + 1]
  cursor = take(cursor.rest, dialect.boosts.length)
  const boost = dialect.boosts[cursor.item]
  const short = sig(noun, adj, adj2, boost)
  if (length === 0) {
    cursor = take(cursor.rest, SHADES.length)
    return { dialect, content: `${SHADES[cursor.item]} ${short}.` }
  }
  if (length === 1) {
    cursor = take(cursor.rest, dialect.openers.length)
    return { dialect, content: `${dialect.openers[cursor.item]}، ${short}.` }
  }
  if (length === 2) {
    cursor = take(cursor.rest, dialect.lines.length)
    return { dialect, content: `${dialect.lines[cursor.item]} ${short}.` }
  }
  cursor = take(cursor.rest, dialect.lines.length)
  const line = dialect.lines[cursor.item]
  cursor = take(cursor.rest, NOTES.length)
  const note = NOTES[cursor.item].replace(/\.$/, '')
  cursor = take(cursor.rest, dialect.tails.length)
  const tail = dialect.tails[cursor.item]
  const detail = topic ? `صار ${topic} أوضح عندي، و${short}` : `${note}، و${short}`
  return { dialect, content: `${line} ${detail}. ${tail}` }
}

function starPlan(target: number, count: number, seed: number) {
  const safe = Math.min(5, Math.max(0, target))
  let total = Math.round(safe * count)
  total = Math.min(count * 5, Math.max(count, total))
  const stars = new Array<number>(count).fill(1)
  let remaining = total - count
  if (count === 0 || remaining <= 0) return stars
  let cursor = seed % count
  let guard = 0
  while (remaining > 0 && guard < count * 6) {
    if (stars[cursor] < 5) {
      stars[cursor] += 1
      remaining -= 1
    }
    cursor = (cursor + 1) % count
    guard += 1
  }
  return stars
}

export function syntheticReviews(input: {
  productId: string
  name: string
  description?: string | null
  category?: string | null
  rating: number
  count: number
}): SyntheticReview[] {
  const count = Math.max(0, Math.round(input.count))
  if (!input.productId || count === 0) return []

  const productName = input.name?.trim() || ''
  const topic = plainTopic(input.description || '', productName)
  const seed = hash32(input.productId)
  const stars = starPlan(input.rating, count, seed)
  const nameSalt = hash32(`${input.productId}|name`)
  const textBase = hash32(`${input.productId}|text`)
  const reviews: SyntheticReview[] = []
  const usedText = new Set<string>()

  for (let index = 0; index < count; index++) {
    const length = index % 4
    const space = phraseSpace(length)
    let phrase = (textBase + index * 199663) % space
    let picked = commentAt(length, phrase, length === 3 && index % 16 === 3 ? topic : '')
    let guard = 0
    while (usedText.has(picked.content) && guard < space) {
      phrase = (phrase + 1) % space
      picked = commentAt(length, phrase, '')
      guard += 1
    }
    usedText.add(picked.content)
    reviews.push({
      id: `synthetic-${input.productId}-${index}`,
      rating: stars[index],
      content: picked.content,
      relativeDate: RELATIVE_DATES[hash32(`${input.productId}|date|${index}`) % RELATIVE_DATES.length],
      place: picked.dialect.places[hash32(`${input.productId}|place|${index}`) % picked.dialect.places.length],
      user: { name: reviewName(nameSalt, index) },
    })
  }

  return reviews
}
