// Reviews written with a masculine first-person adjective get a male name.
const MASCULINE_VOICE = /(مرتاح|متردد|فرحان|مبسوط|خايف|متوقع|عارف|راضي)(?![ةه])/

/**
 * Walks a name pool with a per-product offset and stride (coprime with the
 * pool size), so names never repeat inside a product until the pool is used up
 * and different products start at different places in the pool.
 */
function poolWalker(pool: string[], productId: string, tag: string) {
  const size = pool.length
  const offset = hash32(`${productId}|name|${tag}`) % size
  let stride = 1 + (hash32(`${productId}|stride|${tag}`) % (size - 1))
  while (gcd(stride, size) !== 1) stride = (stride % (size - 1)) + 1
  let index = 0
  return () => pool[(offset + index++ * stride) % size]
}

// Reviews written with a feminine first-person form get a female name.
const FEMININE_VOICE = /(مرتاحة|مترددة|فرحانة|مبسوطة|خايفة|متوقعة|عارفة|راضية)/

export function reviewerGender(name: string): ReviewerGender | null {
  if (MALE.includes(name)) return 'male'
  if (FEMALE.includes(name)) return 'female'
  return null
}

function namePicker(productId: string, next: () => number) {
  const male = poolWalker(MALE, productId, 'm')
  const female = poolWalker(FEMALE, productId, 'f')
  return (content: string): { name: string; gender: ReviewerGender } => {
    const roll = next()
    const gender: ReviewerGender = MASCULINE_VOICE.test(content)
      ? 'male'
      : FEMININE_VOICE.test(content)
        ? 'female'
        : roll < 0.5
          ? 'male'
          : 'female'
    return { name: gender === 'male' ? male() : female(), gender }
  }
}

/** Endless deck: shuffled order, reshuffled each time it runs out. */
function deck<T>(items: T[], next: () => number) {
  let order: T[] = []
  return () => {
    if (order.length === 0) order = shuffled(items, next)
    return order.pop() as T
  }
}

function range(n: number) {
  return Array.from({ length: n }, (_, i) => i)
}

function kindPlan(count: number, next: () => number): Kind[] {
  const emoji = Math.round(count * 0.2)
  const tiny = Math.round(count * 0.17)
  const long = Math.round(count * 0.25)
  const short = Math.max(0, count - emoji - tiny - long)
  const plan: Kind[] = [
    ...new Array<Kind>(emoji).fill('emoji'),
    ...new Array<Kind>(tiny).fill('tiny'),
    ...new Array<Kind>(short).fill('short'),
    ...new Array<Kind>(long).fill('long'),
  ].slice(0, count)
  return shuffled(plan, next)
}

function finish(sentence: string, next: () => number) {
  const roll = next()
  if (/[.!؟?]$/.test(sentence)) return sentence
  if (roll < 0.45) return sentence
  if (roll < 0.75) return `${sentence}.`
  if (roll < 0.9) return `${sentence}!`
  return `${sentence}!!`
}

function withEmoji(text: string, next: () => number, chance: number) {
  if (next() >= chance) return text
  const emoji = TRAILING_EMOJI[Math.floor(next() * TRAILING_EMOJI.length)]
  return `${text} ${next() < 0.3 ? emoji + emoji : emoji}`
}

function starPlan(target: number, count: number, seed: number) {
  const safe = Math.min(5, Math.max(0, target))
  let total = Math.round(safe * count)
  total = Math.min(count * 5, Math.max(count, total))
  const stars = new Array<number>(count).fill(1)
  let remaining = total - count
  if (count === 0 || remaining <= 0) return stars
  let cursor = seed % count
  let guard = 0
  while (remaining > 0 && guard < count * 6) {
    if (stars[cursor] < 5) {
      stars[cursor] += 1
      remaining -= 1
    }
    cursor = (cursor + 1) % count
    guard += 1
  }
  return stars
}

